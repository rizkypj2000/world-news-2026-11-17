const MAP = { latTop: 78, latBottom: -56 };

function inside(lon, lat, poly) {
  let hit = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

function project(lon, lat, w, h) {
  return [((lon + 180) / 360) * w, ((MAP.latTop - lat) / (MAP.latTop - MAP.latBottom)) * h];
}

// pins: [{n, lon, lat, color}]
function drawWorldMap(svg, pins, opts = {}) {
  const w = svg.viewBox.baseVal.width, h = svg.viewBox.baseVal.height;
  const step = opts.step || 2.4;        // degrees between dots
  const r = opts.dot || 1.55;           // dot radius in px
  const ns = 'http://www.w3.org/2000/svg';
  const polys = Object.values(LAND).filter(p => p.length > 2);
  const seas = Object.values(WATER);
  const land = document.createElementNS(ns, 'g');
  land.setAttribute('fill', opts.land || '#b9ad94');
  for (let lat = MAP.latTop - step / 2; lat > MAP.latBottom; lat -= step) {
    for (let lon = -180 + step / 2; lon < 180; lon += step) {
      if (polys.some(p => inside(lon, lat, p)) && !seas.some(s => inside(lon, lat, s))) {
        const [x, y] = project(lon, lat, w, h);
        const c = document.createElementNS(ns, 'circle');
        c.setAttribute('cx', x.toFixed(1)); c.setAttribute('cy', y.toFixed(1)); c.setAttribute('r', r);
        land.appendChild(c);
      }
    }
  }
  svg.appendChild(land);
  for (const p of pins) {
    const [x, y] = project(p.lon, p.lat, w, h);
    const g = document.createElementNS(ns, 'g');
    g.innerHTML = `<circle cx="${x + (p.dx || 0)}" cy="${y + (p.dy || 0)}" r="${p.small ? 3.4 : 7.6}" fill="${p.color}" stroke="#fff" stroke-width="1.4"/>` +
      (p.small ? '' : `<text x="${x + (p.dx || 0)}" y="${y + (p.dy || 0) + 3.4}" text-anchor="middle" font-size="9.6" font-weight="800" fill="#fff" font-family="Segoe UI, Arial">${p.n}</text>`);
    svg.appendChild(g);
  }
}
